"""Детекторы персональных данных.

Каждый детектор возвращает список совпадений (Match) с типом ПД и позициями
в исходной строке. Детекторы построены на regex + словарях — детерминированно
и быстро, без внешних LLM-зависимостей.
"""
from __future__ import annotations

import logging
import re
from collections.abc import Callable, Iterable
from dataclasses import dataclass

logger = logging.getLogger("pii.detectors")


@dataclass(frozen=True)
class Match:
    """Совпадение ПД в тексте."""
    pii_key: str
    start: int
    end: int
    value: str


# ---------------------------------------------------------------------------
# Вспомогательные утилиты
# ---------------------------------------------------------------------------

def _dedupe(matches: Iterable[Match]) -> list[Match]:
    """Убирает вложенные/пересекающиеся совпадения, оставляя самые длинные."""
    ordered = sorted(matches, key=lambda m: (m.start, -(m.end - m.start)))
    result: list[Match] = []
    for m in ordered:
        if result and m.start < result[-1].end:
            # пересечение — оставляем более длинное (уже первое в порядке сортировки)
            continue
        result.append(m)
    return result


