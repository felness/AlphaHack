def detect_phone(text: str) -> list[Match]:
    return [Match("phone", m.start(), m.end(), m.group()) for m in PHONE_RE.finditer(text)]


def detect_email(text: str) -> list[Match]:
    return [Match("email", m.start(), m.end(), m.group()) for m in EMAIL_RE.finditer(text)]


def detect_inn(text: str) -> list[Match]:
    return [Match("inn", m.start(), m.end(), m.group()) for m in INN_RE.finditer(text)]


def detect_card_number(text: str) -> list[Match]:
    matches = []
    for m in CARD_RE.finditer(text):
        # Проверяем по алгоритму Луна ИЛИ наличие ключевого слова "карта" рядом
        context = text[max(0, m.start() - 30):m.end() + 10].lower()
        has_card_kw = any(kw in context for kw in CARD_KEYWORDS)
        if _luhn_valid(m.group()) or has_card_kw:
            matches.append(Match("card_number", m.start(), m.end(), m.group()))
    return matches


def detect_cvv(text: str) -> list[Match]:
    matches = []
    for m in CVV_RE.finditer(text):
        # берём только цифры CVV
        digits = m.group(1)
        start = m.start(1)
        matches.append(Match("cvv", start, start + len(digits), digits))
    return matches


def detect_pin(text: str) -> list[Match]:
    matches = []
    for m in PIN_RE.finditer(text):
        digits = m.group(1) or m.group(2)
        if not digits:
            continue
        start = m.start(1) if m.group(1) else m.start(2)
        matches.append(Match("pin", start, start + len(digits), digits))
    return matches


def detect_passport(text: str) -> list[Match]:
    matches = []
    # Паттерн с разделяющими словами: "серия 4509 номер 123456"
    for m in PASSPORT_WORDS_RE.finditer(text):
        series = m.group(1)
        number = m.group(2)
        # Серия и номер маскируются отдельно (между ними слово "номер")
        matches.append(Match("passport_series_number", m.start(1), m.end(1), series))
        matches.append(Match("passport_series_number", m.start(2), m.end(2), number))
    # Стандартный паттерн: "4509 123456"
    for m in PASSPORT_RE.finditer(text):
        # Проверяем, что рядом есть ключевое слово "паспорт" или "серия"
        context = text[max(0, m.start() - 40):m.end() + 10].lower()
        if any(kw in context for kw in PASSPORT_KEYWORDS):
            matches.append(Match("passport_series_number", m.start(), m.end(), m.group()))
    return _dedupe(matches)


def _detect_with_context(
    text: str,
    pattern: re.Pattern[str],
    keywords: set[str],
    pii_key: str,
    context_before: int = 40,
    context_after: int = 10,
) -> list[Match]:
    """Ищет совпадения паттерна, рядом с которыми есть ключевое слово."""
    matches = []
    for m in pattern.finditer(text):
        context = text[max(0, m.start() - context_before):m.end() + context_after].lower()
        if any(kw in context for kw in keywords):
            matches.append(Match(pii_key, m.start(), m.end(), m.group()))
    return matches


def detect_department_code(text: str) -> list[Match]:
    return _detect_with_context(text, DEPARTMENT_CODE_RE, DEPARTMENT_CODE_KEYWORDS, "passport_department_code")


def detect_driver_license(text: str) -> list[Match]:
    return _detect_with_context(text, DRIVER_LICENSE_RE, DRIVER_LICENSE_KEYWORDS, "driver_license")


def detect_date(text: str) -> list[Match]:
    matches = []
    lower = text.lower()
    for m in DATE_RE.finditer(text):
        # Пропускаем даты, которые являются датой выдачи (после ключевых слов)
        context = lower[max(0, m.start() - 30):m.start()]
        if any(kw in context for kw in ISSUE_DATE_KEYWORDS):
            continue
        matches.append(Match("birth_date", m.start(), m.end(), m.group()))
    for m in DATE_TEXT_RE.finditer(text):
        context = lower[max(0, m.start() - 30):m.start()]
        if any(kw in context for kw in ISSUE_DATE_KEYWORDS):
            continue
        matches.append(Match("birth_date", m.start(), m.end(), m.group()))
    return matches


def detect_issue_date(text: str) -> list[Match]:
    """Детектор даты выдачи паспорта (после ключевых слов 'дата выдачи', 'выдан')."""
    matches = []
    lower = text.lower()
    for kw in ISSUE_DATE_KEYWORDS:
        for m in re.finditer(re.escape(kw), lower):
            # Ищем дату в следующих 30 символах
            after = text[m.end():m.end() + 30]
            for dm in DATE_RE.finditer(after):
                start = m.end() + dm.start()
                end = m.end() + dm.end()
                matches.append(Match("passport_issue_date", start, end, dm.group()))
                break
            for dm in DATE_TEXT_RE.finditer(after):
                start = m.end() + dm.start()
                end = m.end() + dm.end()
                matches.append(Match("passport_issue_date", start, end, dm.group()))
                break
    return _dedupe(matches)


def _is_famous_person(words: list[str]) -> bool:
    """Проверяет, является ли последовательность слов известной персоной."""
    return any(w in FAMOUS_PERSONS for w in words)


# Суффиксы отчеств и фамилий для морфологического распознавания
_PATRONYMIC_SUFFIXES = (
    "ович", "евич", "ич", "овна", "евна", "ична", "инична",
)
_SURNAME_SUFFIXES = (
    "ов", "ёв", "ев", "ин", "ын", "ский", "цкий", "ская", "цкая",
    "ко", "ук", "юк", "ян", "швили", "дзе", "оглы", "уллин", "баев",
    "ова", "ёва", "ева", "ина", "ына", "ских", "цких",
)


def _is_patronymic(word: str) -> bool:
    """Проверяет, похоже ли слово на отчество по суффиксу."""
    if len(word) < 4:
        return False
    return word.endswith(_PATRONYMIC_SUFFIXES)


def _is_surname(word: str) -> bool:
    """Проверяет, похоже ли слово на фамилию по суффиксу."""
    if len(word) < 4:
        return False
    return word.endswith(_SURNAME_SUFFIXES)


def detect_fio(text: str) -> list[Match]:
    """Детектор ФИО на основе словарей + морфологических суффиксных правил."""
    matches = []
    # Строим позиции слов
    positions = []
    for m in re.finditer(r"[А-ЯЁа-яё]+", text):
        positions.append((m.start(), m.end(), m.group().lower()))

    def _famous_after(end_idx: int) -> bool:
        """Проверяет, является ли слово после позиции известной персоной."""
        for j in range(end_idx + 1, len(positions)):
            if positions[j][2] in FAMOUS_PERSONS:
                return True
            break
        return False

    for i in range(len(positions)):
        start, _, w = positions[i]
        is_name = w in RUSSIAN_NAMES
        is_surname = w in RUSSIAN_SURNAMES or _is_surname(w)
        # Имя + отчество
        if is_name and i + 1 < len(positions):
            _, end2, w2 = positions[i + 1]
            if (w2 in RUSSIAN_PATRONYMICS or _is_patronymic(w2)) and not _is_famous_person([w, w2]) and not _famous_after(i + 1):
                matches.append(Match("fio", start, end2, text[start:end2]))
        # Имя + фамилия (2 слова)
        if is_name and i + 1 < len(positions):
            _, end2, w2 = positions[i + 1]
            if (w2 in RUSSIAN_SURNAMES or _is_surname(w2)) and not _is_famous_person([w, w2]) and not _famous_after(i + 1):
                matches.append(Match("fio", start, end2, text[start:end2]))
        # Фамилия + имя (2 слова)
        if is_surname and i + 1 < len(positions):
            _, end2, w2 = positions[i + 1]
            if w2 in RUSSIAN_NAMES and not _is_famous_person([w, w2]) and not _famous_after(i + 1):
                matches.append(Match("fio", start, end2, text[start:end2]))
        # Фамилия + имя + отчество
        if is_surname and i + 2 < len(positions):
            _, end2, w2 = positions[i + 1]
            _, end3, w3 = positions[i + 2]
            if w2 in RUSSIAN_NAMES and (w3 in RUSSIAN_PATRONYMICS or _is_patronymic(w3)) and not _is_famous_person([w, w2, w3]) and not _famous_after(i + 2):
                matches.append(Match("fio", start, end3, text[start:end3]))

    return _dedupe(matches)


def _find_address_keywords(lower: str) -> list[tuple[int, int]]:
    """Находит и объединяет близкие ключевые слова адреса (с границами слов)."""
    kw_positions = []
    for kw in ADDRESS_KEYWORDS:
        # Сокращения с точкой (г., ул., д.) — ищем с точкой, без \b после
        if kw.endswith("."):
            pattern = re.escape(kw)
        else:
            pattern = r"\b" + re.escape(kw) + r"\b"
        for m in re.finditer(pattern, lower):
            kw_positions.append((m.start(), m.end()))

    kw_positions.sort(key=lambda x: x[0])

    merged: list[tuple[int, int]] = []
    for start, end in kw_positions:
        if merged and start < merged[-1][1] + 60:
            merged[-1] = (merged[-1][0], max(merged[-1][1], end))
        else:
            merged.append((start, end))
    return merged


def _expand_address_end(text: str, end: int) -> int:
    """Расширяет адрес до конца предложения или до 120 символов."""
    end_ext = min(len(text), end + 120)
    for sep in [".", ";\n", "\n"]:
        idx = text.find(sep, end)
        if idx != -1 and idx < end_ext:
            end_ext = idx
            break
    return end_ext


