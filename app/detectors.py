# Телефон: +7/8, коды, дефисы/пробелы/скобки
PHONE_RE = re.compile(
    r"(?<!\d)(?:\+7|8|7)[\s\-]*(?:\(\d{3}\)|\d{3})[\s\-]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}(?!\d)"
)

# Email
EMAIL_RE = re.compile(
    r"(?<![A-Za-z0-9._%+-])[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}(?![A-Za-z0-9._%+-])"
)

# ИНН: 10 или 12 цифр
INN_RE = re.compile(r"(?<!\d)\d{10}(?!\d)|(?<!\d)\d{12}(?!\d)")

# Номер карты: 16 цифр, сгруппированы по 4
CARD_RE = re.compile(
    r"(?<!\d)(?:\d{4}[\s\-]?){3}\d{4}(?!\d)"
)

# CVV: 3 цифры после ключевого слова
CVV_RE = re.compile(r"(?i)(?:cvv|cvc|cvv2|cvc2|код безопасности|код проверки)[\s:]*(\d{3})")

# ПИН: 4 цифры после ключевого слова
PIN_RE = re.compile(r"(?i)(?:пин|пин-код|пинкод|pin)[\s\-]*код[\s:]*(\d{4})|(?:пин|pin)[\s:]*(\d{4})")

# Серия и номер паспорта: 4 цифры + 6 цифр (с разделителями)
PASSPORT_RE = re.compile(
    r"(?<!\d)(?:\d{2}[\s\-]?\d{2})[\s\-]+(?:\d{6})(?!\d)"
)

# Серия и номер паспорта с разделяющими словами: "серия 4509 номер 123456"
PASSPORT_WORDS_RE = re.compile(
    r"(?i)(?:серия|серии)[\s:]*(\d{2}[\s\-]?\d{2})[\s,;]*(?:номер|№|n)[\s:]*(\d{6})"
)

# Код подразделения: XXX-XXX
DEPARTMENT_CODE_RE = re.compile(r"(?<!\d)\d{3}[\s\-]\d{3}(?!\d)")

# Серия и номер водительского удостоверения: 4 цифры + 6 цифр
DRIVER_LICENSE_RE = re.compile(
    r"(?<!\d)(?:\d{2}[\s\-]?\d{2})[\s\-]+(?:\d{6})(?!\d)"
)

# Дата: различные форматы
DATE_RE = re.compile(
    r"(?<!\d)(?:\d{1,2}[./-]\d{1,2}[./-]\d{2,4}|\d{4}[./-]\d{1,2}[./-]\d{1,2})(?!\d)"
)

# Дата текстом: "12 января 1990"
DATE_TEXT_RE = re.compile(
    r"(?<!\d)(?:\d{1,2}\s+(?:января|февраля|марта|апреля|мая|июня|июля|августа|сентября|октября|ноября|декабря)\s+\d{4})(?!\d)"
)


def _luhn_valid(number: str) -> bool:
    """Проверяет номер карты по алгоритму Луна."""
    digits = [int(d) for d in number if d.isdigit()]
    if len(digits) < 13:
        return False
    checksum = 0
    for i, d in enumerate(reversed(digits)):
        if i % 2 == 1:
            d *= 2
            if d > 9:
                d -= 9
        checksum += d
    return checksum % 10 == 0

